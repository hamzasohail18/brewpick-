// Generates supabase/seeds/03_sample_data.sql from data.ts. Deterministic: ids are md5 of stable
// keys, prices use a fixed hash, so regenerating gives the same file.
//
//   npm run sample:generate

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseOpeningHours } from "@collectors/osm/opening-hours";
import {
  BRANDS,
  CAFFEINE_PER_SHOT_MG,
  DEALS,
  DRINKS,
  MILK_SUGAR_G_PER_100,
  MILK_SWAPS,
  PLACES,
  WHOLE_MILK_KCAL_PER_100,
  type SampleDrink,
  type SamplePlace,
  type SampleSize,
} from "./data";

const q = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${v.replace(/'/g, "''")}'`);
const b = (v: boolean | null) => (v === null ? "null" : v ? "true" : "false");
const id = (...parts: string[]) => `md5(${q(`sample:${parts.join(":")}`)})::uuid`;
const SOURCE = "(select id from sources where slug = 'sample-data')";
const area = (name: string, col: "id" | "centroid_lat" | "centroid_lng") => `(select ${col} from areas where name = ${q(name)})`;

/** FNV-1a, for stable pseudo-random price variation. */
function hash(s: string) {
  let h = 0x811c9dc5;
  for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 0x01000193) >>> 0;
  return h;
}

export function samplePrice(place: SamplePlace, drink: SampleDrink, size: SampleSize) {
  const jitter = 0.96 + (hash(`${place.slug}:${drink.slug}:${size.label}`) % 9) / 100; // 0.96–1.04
  return Math.round((size.basePkr * place.tier * jitter) / 10) * 10;
}

export function sampleNutrition(drink: SampleDrink, size: SampleSize) {
  const espressoKcal = size.shots * 1;
  const kcal = Math.round(espressoKcal + (size.milkMl * WHOLE_MILK_KCAL_PER_100) / 100 + (size.extra?.kcal ?? 0) + (drink.slug === "cold-brew" ? 5 : 0));
  const sugar = Math.round(((size.milkMl * MILK_SUGAR_G_PER_100) / 100 + (size.extra?.sugarG ?? 0)) * 10) / 10;
  const caffeine = size.caffeineMg ?? size.shots * CAFFEINE_PER_SHOT_MG;
  const parts = [
    size.shots ? `${size.shots} espresso shot${size.shots > 1 ? "s" : ""}` : "cold brew concentrate",
    size.milkMl ? `${size.milkMl} ml full-fat milk` : "no milk",
    size.extra?.what,
    "no added sugar",
  ].filter(Boolean);
  return { kcal, sugar, caffeine, assumptions: `Sample estimate: ${parts.join(", ")}.` };
}

export function buildSampleSql(): string {
  const out: string[] = [];
  const push = (s: string) => out.push(s);

  push(`-- SAMPLE DATA: FICTIONAL. Generated by scripts/sample-data/generate.ts from data.ts. Do not edit by hand.
-- Every row is placeholder data for development (is_sample = true, "Sample data" badge in the UI).
-- Remove with: npm run sample:purge   (or the button on /admin/import)
`);

  push(`insert into sources (slug, name, kind, automation, automation_notes, default_confidence, check_interval_days)
values ('sample-data', 'Sample data (fictional)', 'manual_admin', 'allowed',
        'Fictional placeholder data for development and demos. Not real prices or deals. Remove with npm run sample:purge.',
        'estimated', 365)
on conflict (slug) do nothing;
`);

  for (const br of BRANDS) {
    push(`insert into brands (id, slug, name, is_sample) values (${id("brand", br.slug)}, ${q(br.slug)}, ${q(br.name)}, true) on conflict do nothing;`);
  }

  for (const p of PLACES) {
    const pid = id("place", p.slug);
    const verified = `now() - interval '${p.verifiedDaysAgo} days'`;
    push(`
-- ${p.name}${p.branch ? ` (${p.branch})` : ""}
insert into places (id, slug, name, branch_name, brand_id, type, area_id, address, lat, lng, halal_certified, has_wifi,
                    has_family_seating, has_drive_thru, rating_avg, rating_count, status, is_sample, source_id, confidence, last_verified_at)
values (${pid}, ${q(p.slug)}, ${q(p.name)}, ${q(p.branch)}, ${p.brand ? id("brand", p.brand) : "null"}, '${p.type}', ${area(p.area, "id")},
        ${q(`Sample address, ${p.area}, Lahore`)}, ${area(p.area, "centroid_lat")} + ${p.offset[0]}, ${area(p.area, "centroid_lng")} + ${p.offset[1]},
        ${b(p.halal)}, ${b(p.wifi)}, ${b(p.family)}, ${b(p.type === "kiosk_drive_thru")}, ${p.rating}, ${p.ratings}, 'published', true,
        ${SOURCE}, '${p.priceConfidence}', ${verified})
on conflict do nothing;`);

    const hours = parseOpeningHours(p.hours);
    if (!hours) throw new Error(`Bad hours for ${p.slug}: ${p.hours}`);
    push(
      `insert into place_hours (place_id, day_of_week, opens_at, closes_at, is_closed) values\n` +
        hours.map((h) => `  (${pid}, ${h.day_of_week}, ${q(h.opens)}, ${q(h.closes)}, ${h.is_closed})`).join(",\n") +
        `\non conflict (place_id, day_of_week) do nothing;`,
    );

    if (p.beans) {
      const bn = p.beans;
      push(`insert into bean_info (id, place_id, kind, origin_country, origin_region, roaster, roast, arabica_pct, robusta_pct, tasting_notes,
                       source_id, confidence, captured_at, last_verified_at)
values (${id("beans", p.slug)}, ${pid}, '${bn.kind}', ${q(bn.origin)}, ${q(bn.region)}, ${q(`${p.name} (sample roaster)`)}, '${bn.roast}',
        ${bn.arabica}, ${bn.robusta}, ${q(bn.notes)}, ${SOURCE}, 'community_reported', ${verified}, ${verified})
on conflict do nothing;`);
    }

    for (const slug of p.drinks) {
      const d = DRINKS.find((x) => x.slug === slug);
      if (!d) throw new Error(`Unknown drink ${slug}`);
      const mid = id("item", p.slug, d.slug);
      const hasMilk = d.sizes.some((s) => s.milkMl > 0);
      const veganPossible = !hasMilk || p.milkOptions.some((m) => m === "oat" || m === "almond");
      push(`insert into menu_items (id, place_id, drink_type_id, display_name, temperature, espresso_shots, has_milk, is_vegan_possible, status, is_sample)
values (${mid}, ${pid}, (select id from drink_types where slug = ${q(d.slug)}), ${q(d.name)}, '${d.temperature}', ${d.sizes[0].shots || "null"},
        ${hasMilk}, ${veganPossible}, 'published', true)
on conflict do nothing;`);

      for (const ing of d.ingredients) {
        push(`insert into item_ingredients (menu_item_id, ingredient_id) select ${mid}, id from ingredients where name = ${q(ing)} on conflict do nothing;`);
      }
      if (hasMilk) {
        push(`insert into item_allergens (menu_item_id, allergen_id, confidence) select ${mid}, id, 'estimated' from allergens where code = 'dairy' on conflict do nothing;`);
        const refMilk = d.sizes[0].milkMl;
        for (const m of p.milkOptions) {
          const swap = MILK_SWAPS[m];
          const extraKcal = Math.round((refMilk * (swap.kcalPer100 - WHOLE_MILK_KCAL_PER_100)) / 100);
          push(`insert into item_milk_options (menu_item_id, milk_type_id, extra_price_pkr, extra_kcal)
select ${mid}, id, ${swap.extraPkr}, ${extraKcal} from milk_types where slug = '${m}' on conflict do nothing;`);
        }
      }

      for (const s of d.sizes) {
        const sid = id("size", p.slug, d.slug, s.label);
        const n = sampleNutrition(d, s);
        push(`insert into item_sizes (id, menu_item_id, size_label, volume_ml, volume_is_assumed) values (${sid}, ${mid}, ${q(s.label)}, ${s.ml}, false) on conflict do nothing;
insert into item_prices (id, item_size_id, channel, price_pkr, tax_inclusive, is_current, source_id, confidence, captured_at, last_verified_at)
values (${id("price", p.slug, d.slug, s.label)}, ${sid}, 'dine_in', ${samplePrice(p, d, s)}, true, true, ${SOURCE}, '${p.priceConfidence}', ${verified}, ${verified})
on conflict do nothing;
insert into nutrition_info (id, item_size_id, calories_kcal, sugar_g, caffeine_mg, assumptions, source_id, confidence, captured_at, last_verified_at)
values (${id("nutrition", p.slug, d.slug, s.label)}, ${sid}, ${n.kcal}, ${n.sugar}, ${n.caffeine}, ${q(n.assumptions)}, ${SOURCE}, 'estimated', ${verified}, ${verified})
on conflict do nothing;`);
      }
    }
  }

  push("\n-- Deals (dates are relative to when the seed runs)");
  for (const d of DEALS) {
    const did = id("deal", d.key);
    const days = d.days ? `'{${d.days.join(",")}}'::smallint[]` : "null";
    push(`insert into deals (id, place_id, brand_id, title, deal_type, discount, discount_value, max_discount_pkr, min_spend_pkr,
                   valid_from, valid_to, days_of_week, start_time, end_time, terms, applies_to_all_items, status, is_sample,
                   source_id, source_url, confidence, last_verified_at)
values (${did}, ${d.place ? id("place", d.place) : "null"}, ${d.brand ? id("brand", d.brand) : "null"}, ${q(d.title)}, '${d.dealType}', '${d.discount}',
        ${d.value ?? "null"}, ${d.cap ?? "null"}, ${d.minSpend ?? "null"}, current_date + ${d.fromDays}, current_date + ${d.toDays}, ${days},
        ${q(d.start)}, ${q(d.end)}, ${q(d.terms)}, ${!d.items}, 'published', true, ${SOURCE}, 'https://brewpick.example/sample-data',
        'community_reported', now())
on conflict do nothing;`);
    for (const c of d.cards ?? []) {
      push(`insert into deal_payment_methods (deal_id, payment_method_id) select ${did}, id from payment_methods where name = ${q(c)} on conflict do nothing;`);
    }
    for (const item of d.items ?? []) {
      push(`insert into deal_items (deal_id, menu_item_id) values (${did}, ${id("item", d.place!, item)}) on conflict do nothing;`);
    }
    for (const c of d.conditions ?? []) {
      push(`insert into deal_conditions (deal_id, condition_key)
select ${did}, ${q(c)} where not exists (select 1 from deal_conditions where deal_id = ${did} and condition_key = ${q(c)});`);
    }
  }
  return out.join("\n") + "\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = fileURLToPath(new URL("../../supabase/seeds/03_sample_data.sql", import.meta.url));
  writeFileSync(target, buildSampleSql());
  console.log(`Wrote ${target}`);
}
